import { chromium, expect } from '@playwright/test'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'

const baseURL = process.env.SITE_URL || 'http://127.0.0.1:5173'
const executablePath = [process.env.BROWSER_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p => p && existsSync(p))
const browser = await chromium.launch({ executablePath, headless: true, args: ['--use-angle=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist'] })
const report = { checks: [], errors: [], viewports: [] }
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' })
const page = await context.newPage()
page.on('pageerror', err => report.errors.push(err.message))
function assert(value, message) { if (!value) throw new Error(message); report.checks.push(message) }

try {
  await page.goto(baseURL, { waitUntil: 'networkidle' })
  await page.locator('h1').waitFor()
  await page.evaluate(() => document.fonts.ready)
  await page.locator('.bouquet-render[data-ready="true"]').waitFor({ timeout: 30000 })
  const canvas = page.locator('.bouquet-render canvas')
  const roseImage = await canvas.screenshot()
  await page.getByRole('button', { name: 'Lilac dream', exact: true }).click()
  await expect.poll(async () => !(await canvas.screenshot()).equals(roseImage)).toBe(true)
  assert(await page.getByRole('button', { name: 'Lilac dream', exact: true }).getAttribute('aria-pressed') === 'true', 'Colour mood changes the rendered bouquet')
  await page.getByRole('button', { name: 'Rose pink', exact: true }).click()
  await canvas.focus()
  const frontImage = await canvas.screenshot()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(async () => !(await canvas.screenshot()).equals(frontImage)).toBe(true)
  assert(true, 'Keyboard arrows rotate the rendered bouquet')
  await page.keyboard.press('Home')
  assert(await page.locator('.product-card').count() === 11, 'All eleven studio creations are visible')
  assert(await page.locator('video').count() === 0, 'Product videos are not loaded before a visitor requests one')
  await page.getByRole('button', { name: 'Flowerpots', exact: true }).click()
  assert(await page.locator('.product-card').count() === 6 && await page.getByRole('heading', { name: 'Happiness, potted' }).isVisible(), 'Flowerpot filter shows six photographed pots')
  await page.getByRole('button', { name: 'Hair clips', exact: true }).click()
  assert(await page.locator('.product-card').count() === 1 && await page.getByRole('heading', { name: 'Sunshine in your hair' }).isVisible(), 'Hair clips have their own category')
  await page.getByRole('button', { name: 'Keychains', exact: true }).click()
  assert(await page.locator('.product-card').count() === 4, 'Keychain filter shows four photographed keychains')
  await page.getByRole('button', { name: 'Save The little bloom keychain', exact: true }).click()
  await page.getByRole('button', { name: 'Saved (1)', exact: true }).click()
  assert(await page.locator('.product-card').count() === 1, 'Saved view contains the favourite')
  await page.reload({ waitUntil: 'networkidle' })
  assert(await page.getByRole('button', { name: 'Unsave The little bloom keychain', exact: true }).getAttribute('aria-pressed') === 'true', 'Favourites survive a reload')
  await page.getByRole('button', { name: 'Explore Happiness, potted', exact: true }).click()
  assert(await page.locator('.product-dialog').isVisible(), 'Creation details open in a native dialog')
  await page.getByRole('button', { name: 'Watch video', exact: true }).click()
  const productVideo = page.locator('.product-dialog video')
  await expect.poll(() => productVideo.evaluate(video => video.readyState)).toBeGreaterThanOrEqual(2)
  assert(await productVideo.evaluate(video => video.paused && video.muted && video.controls && video.playsInline), 'Video waits for playback and provides muted inline native controls')
  await productVideo.evaluate(video => video.play())
  await expect.poll(() => productVideo.evaluate(video => video.currentTime)).toBeGreaterThan(0.1)
  assert(true, 'The supplied product video plays successfully')
  await page.getByRole('button', { name: 'Photo', exact: true }).click()
  assert(await page.locator('.product-dialog video').count() === 0, 'Returning to the photo removes the playing video')
  if (process.argv.includes('--capture')) {
    mkdirSync('.impeccable/review', { recursive: true })
    await page.screenshot({ path: '.impeccable/review/product-dialog.png', animations: 'disabled' })
  }
  await page.getByRole('button', { name: 'Make it my own', exact: true }).click()
  assert(await page.locator('.enquiry-dialog').isVisible(), 'Creation enquiry carries through from its details')
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill(' ')
  await page.getByRole('textbox', { name: 'Email address', exact: true }).fill('test@example.com')
  await page.getByRole('textbox', { name: 'A little about your idea', exact: true }).fill('Pink and yellow flowers for a birthday.')
  await page.getByRole('button', { name: 'Put my enquiry together', exact: true }).click()
  assert(await page.locator('input[name="name"]').evaluate(el => !el.validity.valid), 'Whitespace-only names are rejected')
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Test Visitor')
  await page.getByRole('button', { name: 'Put my enquiry together', exact: true }).click()
  const note = await page.getByRole('textbox', { name: 'Your prepared enquiry' }).inputValue()
  assert(await page.getByRole('textbox', { name: 'Your prepared enquiry' }).evaluate(el => el === document.activeElement), 'Prepared enquiry receives keyboard focus')
  assert(note.includes('Happiness, potted') && note.includes('Test Visitor') && note.includes('test@example.com'), 'Prepared enquiry includes the chosen creation and visitor details')
  assert(await page.getByText('Nothing has been sent or booked yet.').isVisible(), 'Enquiry result accurately discloses that it has not been sent')
  await page.getByRole('button', { name: 'Copy enquiry', exact: true }).click()
  await page.getByRole('button', { name: 'Copied to clipboard', exact: true }).waitFor()
  const copiedNote = await page.evaluate(() => navigator.clipboard.readText())
  assert(copiedNote.replaceAll('\r\n', '\n') === note.replaceAll('\r\n', '\n'), 'Copy enquiry writes the exact note to the clipboard')
  await page.keyboard.press('Escape')
  assert(await page.locator('dialog').count() === 0, 'Escape closes the dialog')
  await page.getByRole('button', { name: 'Find your creative side', exact: true }).click()
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Workshop Visitor')
  await page.getByRole('textbox', { name: 'Email address', exact: true }).fill('workshop@example.com')
  await page.getByRole('combobox', { name: 'How many people?' }).selectOption({ label: '6–12 people' })
  await page.getByRole('textbox', { name: 'A little about your idea', exact: true }).fill('A creative afternoon for our friends in Hyderabad.')
  await page.getByRole('button', { name: 'Put my enquiry together', exact: true }).click()
  assert((await page.getByRole('textbox', { name: 'Your prepared enquiry' }).inputValue()).includes('6–12 people'), 'Workshop enquiry includes the selected group size')
  await page.keyboard.press('Escape')
  assert(await page.getByRole('button', { name: 'Find your creative side', exact: true }).evaluate(el => el === document.activeElement), 'Closing workshop enquiry restores focus to its trigger')
  await page.getByRole('button', { name: 'Can I ask for something in my favourite colours?' }).click()
  assert(await page.locator('#faq-answer-1').isVisible() && !await page.locator('#faq-answer-0').isVisible(), 'FAQ answers expand and collapse correctly')
  await page.getByRole('button', { name: 'Play motion', exact: true }).click()
  assert(await page.getByRole('button', { name: 'Pause motion', exact: true }).isVisible(), 'Motion control toggles its accessible state')
  await page.getByRole('button', { name: 'Pause motion', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('twist-bloom-favourites', '{"corrupt":true}'))
  await page.reload({ waitUntil: 'networkidle' })
  assert(await page.locator('.product-card').count() === 11, 'Malformed local storage does not break the page')
  await page.setViewportSize({ width: 375, height: 900 })
  await page.getByRole('combobox', { name: 'Show creations', exact: true }).selectOption('Flowerpots')
  assert(await page.locator('.product-card').count() === 6, 'Mobile category selector filters flowerpots')
  await page.getByRole('combobox', { name: 'Show creations', exact: true }).selectOption('All creations')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  assert(await page.getByRole('navigation', { name: 'Mobile navigation', exact: true }).isVisible(), 'Mobile navigation opens')
  await page.getByRole('navigation', { name: 'Mobile navigation', exact: true }).getByRole('link', { name: 'Our story', exact: true }).focus()
  await page.keyboard.press('Escape')
  assert(await page.getByRole('button', { name: 'Open navigation', exact: true }).evaluate(el => el === document.activeElement), 'Escape returns mobile menu focus to its toggle')
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('navigation', { name: 'Mobile navigation', exact: true }).getByRole('link', { name: 'Workshops', exact: true }).click()
  assert(await page.locator('#mobile-nav').count() === 0 && new URL(page.url()).hash === '#workshops', 'Mobile navigation closes after visiting the selected section')
  await page.evaluate(() => localStorage.removeItem('twist-bloom-favourites'))

  const fallbackPage = await context.newPage()
  await fallbackPage.addInitScript(() => {
    const nativeContext = HTMLCanvasElement.prototype.getContext
    HTMLCanvasElement.prototype.getContext = function (type, ...args) { return String(type).includes('webgl') ? null : nativeContext.call(this, type, ...args) }
  })
  await fallbackPage.goto(baseURL, { waitUntil: 'networkidle' })
  await fallbackPage.locator('.bouquet-render[data-fallback="true"]').waitFor()
  assert(await fallbackPage.locator('.bouquet-fallback').isVisible() && await fallbackPage.locator('.bouquet-fallback').evaluate(img => img.naturalWidth > 0), 'Static bouquet remains visible when WebGL is unavailable')
  await fallbackPage.close()

  if (process.argv.includes('--capture')) {
    mkdirSync('.impeccable/review', { recursive: true })
    for (const width of [1440, 1280, 320, 375, 414, 768]) {
      await page.setViewportSize({ width, height: width === 1440 ? 1000 : width === 1280 ? 800 : 900 })
      await page.goto(baseURL, { waitUntil: 'networkidle' })
      await page.evaluate(async () => {
        await document.fonts.ready
        document.querySelectorAll('img').forEach(img => img.loading = 'eager')
        await Promise.all(Array.from(document.images, img => img.decode().catch(() => {})))
        window.scrollTo(0, 0)
      })
      await page.locator('.bouquet-render[data-ready="true"], .bouquet-render[data-fallback="true"]').waitFor({ timeout: 30000 })
      const metrics = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, brokenImages: Array.from(document.images).filter(img => !img.complete || img.naturalWidth === 0).map(img => img.src) }))
      report.viewports.push(metrics)
      assert(metrics.scrollWidth <= width, `No horizontal overflow at ${width}px`)
      assert(metrics.brokenImages.length === 0, `All images loaded at ${width}px`)
      const filename = width === 1440 ? 'desktop' : width === 375 ? 'mobile' : `user-${width}`
      await page.screenshot({ path: `.impeccable/review/${filename}.png`, fullPage: true, animations: 'disabled' })
      if (width === 1440) await page.screenshot({ path: '.impeccable/review/desktop-hero.png', animations: 'disabled' })
      if (width === 1280) await page.screenshot({ path: '.impeccable/review/laptop-hero.png', animations: 'disabled' })
    }
  }
  assert(report.errors.length === 0, 'No uncaught browser errors')
  mkdirSync('.impeccable/review', { recursive: true })
  writeFileSync('.impeccable/review/checks.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally { await browser.close() }
